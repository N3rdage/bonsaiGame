export const GLYPH_HEIGHT = 7;

/** The width in pixels of `text` drawn at `scale`, without a trailing gap. */
export function textWidth(text, scale) {
  return text.length === 0 ? 0 : (text.length * 6 - 1) * scale;
}

/** Calls `plot(x, y)` for every ink pixel of `text` drawn at `scale` with its top-left at (x, y). */
export function rasterize(text, x, y, scale, plot) {
  [...text].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`sitePlanFont: no glyph for ${JSON.stringify(ch)}`);
    glyph.forEach((row, gy) => {
      [...row].forEach((cell, gx) => {
        if (cell !== '#') return;
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            plot(x + (i * 6 + gx) * scale + dx, y + gy * scale + dy);
          }
        }
      });
    });
  });
}
